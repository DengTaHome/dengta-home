-- whereabouts-mcp 多租户集成：行踪上下文（停留/移动/电量趋势）
-- 每个用户（user_id+companion_id）独立存储：原始上报点 + 聚合状态

create table if not exists public.whereabouts_points (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  companion_id uuid not null,
  latitude double precision not null,
  longitude double precision not null,
  battery_level integer,
  trigger text,
  address text,
  point_time timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists whereabouts_points_tenant_time_idx
  on public.whereabouts_points (user_id, companion_id, point_time desc);

create table if not exists public.whereabouts_state (
  user_id uuid not null,
  companion_id uuid not null,
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (user_id, companion_id)
);

alter table public.whereabouts_points enable row level security;
alter table public.whereabouts_state enable row level security;

drop policy if exists "whereabouts_points_owner_all" on public.whereabouts_points;
create policy "whereabouts_points_owner_all"
  on public.whereabouts_points
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "whereabouts_state_owner_all" on public.whereabouts_state;
create policy "whereabouts_state_owner_all"
  on public.whereabouts_state
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
