"use strict";
const assert = require("node:assert/strict");
const path = require("node:path");
const { diagnosticRecord, publicDiagnosticLog } = require("../services/diagnostic-errors");
const error = Object.assign(new Error("private-fixture sk-not-a-real-secret"), { status: 500, code: "request_timeout" });
error.stack = `Error: private-fixture\n    at operation (${path.resolve(__dirname, "../server.js")}:100:20)\n    at private (https://example.test/private?token=fixture:1:2)`;
const result = diagnosticRecord({ route: { path: "/api/v2/sessions/:id/messages" }, method: "POST", body: { model: "private-model", secret: "private-fixture", stream: true } }, error);
assert.equal(result.stack_trace, "server.js:100:20");
assert.equal(result.error_code, "request_timeout");
assert.equal(result.request_summary.stream, true);
assert.equal(diagnosticRecord({ route: { path: "/chat/stream" }, method: "POST", body: {} }, error).request_summary.stream, true);
assert.ok(!JSON.stringify(result).includes("private"));
const publicRow = publicDiagnosticLog({ ...result, id: "fixture-id", created_at: "2026-09-28T00:00:00Z", message: "private-fixture", request_summary: { model: "private-fixture", stream: true } });
assert.equal(publicRow.error_location, "server.js:100:20");
assert.ok(!JSON.stringify(publicRow).includes("private"));
const legacy = publicDiagnosticLog({ stack_trace: "Error: private-fixture\n    at unknown (C:/private/file.js:1:2)", message: "private-fixture", path: "/private-fixture?token=private-fixture", error_code: "private-fixture" });
assert.ok(!JSON.stringify(legacy).includes("private"));
assert.equal(legacy.stack_trace, "");
console.log("Diagnostics: precise business frames, stable codes, metadata-only persistence and safe legacy display passed");

const budgetRecord = diagnosticRecord({method:'POST',route:{path:'/chat/stream'}}, {code:'context_budget_exceeded',budgetStage:'transport',budgetUsage:{capacity:65536,input:50000,reservedOutput:32000,privateText:'do not include'}});
const budgetPublic = publicDiagnosticLog(budgetRecord);
assert.deepEqual(budgetPublic.request_summary.context_budget, {capacity:65536,input:50000,reservedOutput:32000,stage:'transport'});
assert.ok(!JSON.stringify(budgetPublic).includes('privateText'));
const importRecord = diagnosticRecord({method:'POST',route:{path:'/api/v2/memory/import-file'}}, {code:'memory_import_endpoint_not_found',status:502,errorSource:'external_memory_gateway',upstreamStatus:404,message:'private provider body'});
assert.equal(importRecord.error_code,'memory_import_endpoint_not_found');
assert.equal(importRecord.path,'/api/v2/memory/import-file');
assert.equal(publicDiagnosticLog(importRecord).error_source,'external_memory_gateway');
assert.equal(publicDiagnosticLog(importRecord).upstream_status,404);
assert.ok(!JSON.stringify(importRecord).includes('private provider body'));
